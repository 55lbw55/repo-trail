"""Git plumbing for isolated reviews, with no checkout of upstream code."""

import os
import re
import subprocess
import tempfile
import tomllib
from pathlib import Path

from .github import WorkbenchError


def git(directory, *args, data=None, index=None):
    env = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
    env.update(GIT_TERMINAL_PROMPT="0", GIT_NO_REPLACE_OBJECTS="1", GIT_NO_LAZY_FETCH="1",
               GIT_ATTR_NOSYSTEM="1")
    if index:
        env["GIT_INDEX_FILE"] = str(index)
    try:
        result = subprocess.run(
            ["git", "-c", f"core.hooksPath={os.devnull}", "-c", "commit.gpgSign=false",
             "-c", "core.fsmonitor=false", "-c", "core.autocrlf=false", "-c", "core.whitespace=cr-at-eol",
             "-c", f"core.attributesFile={os.devnull}", *args],
            cwd=directory, input=data, capture_output=True, env=env, timeout=30,
        )
    except (OSError, subprocess.TimeoutExpired):
        raise WorkbenchError("Git 无法运行或超时。") from None
    if result.returncode:
        raise WorkbenchError(f"Git {args[0]} 失败，请核对仓库状态、分支、补丁或本地 Git 身份。")
    return result.stdout


def normalize_package(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def dependencies(document):
    values = document.get("project", {}).get("dependencies", [])
    if not isinstance(values, list) or any(not isinstance(item, str) for item in values):
        raise WorkbenchError("无法解析项目的 PEP 621 依赖数组。")
    return {
        normalize_package(match.group()) for value in values
        if (match := re.match(r"[A-Za-z0-9][A-Za-z0-9._-]*", value))
    }


def parse_manifest(data):
    try:
        return tomllib.loads(data.decode("utf-8"))
    except (ValueError, UnicodeError):
        raise WorkbenchError("无法读取 UTF-8 TOML 项目清单。") from None


def project_dependencies(project):
    manifest = project / "pyproject.toml"
    return dependencies(parse_manifest(manifest.read_bytes())) if manifest.is_file() else set()


def add_dependency(data, requirement):
    document = parse_manifest(data)
    name = normalize_package(re.split(r"[<=>!~]", requirement)[0])
    if name in dependencies(document):
        raise WorkbenchError("基础 commit 已声明同名依赖。")
    old = data.decode()
    new = old
    newline = "\r\n" if "\r\n" in old else "\n"
    section = re.search(r"(?m)^\[project\][ \t]*(?:#[^\r\n]*)?\r?\n", old)
    if not section or "project" not in document:
        raise WorkbenchError("写入仅支持常规 PEP 621 [project] 清单。")
    next_section = re.compile(r"(?m)^\s*\[").search(old, section.end())
    end = next_section.start() if next_section else len(old)
    array = re.compile(r"(?m)^[ \t]*dependencies[ \t]*=[ \t]*\[").search(old, section.end(), end)
    if array:
        remainder = old[array.end():]
        value = f'"{requirement}",'
        if remainder.startswith(newline):
            new = old[:array.end()] + newline + "    " + value + remainder
        else:
            new = old[:array.end()] + value + " " + remainder
    elif "dependencies" not in document["project"] and "dependencies" not in document["project"].get("dynamic", []):
        new = old[:section.end()] + f'dependencies = ["{requirement}"]' + newline + old[section.end():]
    expected = document["project"].setdefault("dependencies", [])
    expected.insert(0, requirement)
    if parse_manifest(new.encode()) != document:
        raise WorkbenchError("清单布局无法安全保留，请人工修改。")
    return new.encode()


def isolated_review(project, branch, changes, patch, requirement=None):
    if not re.fullmatch(r"workbench/[a-z0-9][a-z0-9-]{0,80}", branch):
        raise WorkbenchError("隔离分支格式为 workbench/小写字母数字或短横线。")
    # Paths are generated by the CLI. A temporary index keeps HEAD and the user's index untouched.
    root = Path(os.fsdecode(git(project, "rev-parse", "--show-toplevel").rstrip(b"\r\n")))
    if root.resolve() != project.resolve():
        raise WorkbenchError("生成分支时，--project 须指向 Git 工作树根目录。")
    base = git(project, "rev-parse", "--verify", "HEAD^{commit}").strip().decode("ascii")
    ref = f"refs/heads/{branch}"
    if git(project, "for-each-ref", "--format=%(refname)", ref):
        raise WorkbenchError("隔离分支名已占用，请更换。")
    if requirement:
        manifest = git(project, "cat-file", "blob", f"{base}:pyproject.toml")
        changes = {"pyproject.toml": add_dependency(manifest, requirement), **changes}
    with tempfile.TemporaryDirectory(prefix="workbench-index-") as temporary:
        index = Path(temporary) / "index"
        git(project, "read-tree", base, index=index)
        for path, content in changes.items():
            entry = git(project, "ls-tree", base, "--", path)
            if entry and (path != "pyproject.toml" or not entry.startswith(b"100644 blob ")):
                raise WorkbenchError("变更路径已占用或文件模式超出第一版支持范围。")
            blob = git(project, "hash-object", "-w", "--no-filters", "--stdin", data=content).strip().decode()
            git(project, "update-index", "--add", "--cacheinfo", f"100644,{blob},{path}", index=index)
        git(project, "diff", "--cached", "--no-ext-diff", "--no-textconv", "--check", base, index=index)
        diff = git(project, "diff", "--cached", "--no-ext-diff", "--no-textconv", "--binary",
                   "--no-renames", "--unified=0", base, index=index)
        tree = git(project, "write-tree", index=index).strip().decode()
        commit = git(project, "commit-tree", tree, "-p", base, "-m", "Prepare open-source reuse review").strip().decode()
        with patch.open("xb") as stream:
            stream.write(diff)
        try:
            git(project, "update-ref", ref, commit, "0" * len(base))
        except WorkbenchError:
            patch.unlink()
            raise
