"""Evidence-led contribution drafts and verified, local-only text patches."""

import ast
import difflib
import json
import re
import tempfile
from pathlib import Path, PureWindowsPath

from .github import WorkbenchError, public_path
from .local import git
from .reuse import inline, terms

AI_LINE = re.compile(r"\b(?:AI|LLMs?|ChatGPT|Claude|Copilot|generated by|generative|maintainer approval|approved by a maintainer)\b", re.I)
KINDS = {"docs": "文档或示例不一致", "platform": "普通跨平台兼容问题", "good-first": "good first issue"}


def issue_link(snapshot, row):
    kind = "pull" if "pull_request" in row else "issues"
    return f"https://github.com/{snapshot.repo}/{kind}/{int(row['number'])}"


def claim(document, name):
    data = document.get(name)
    if not isinstance(data, dict) or not all(isinstance(data.get(key), str) and data[key] for key in ("path", "text")):
        raise WorkbenchError(f"证据 JSON 须包含 {name}.path 和 {name}.text。")
    return public_path(data["path"]), data["text"]


def locate(source, exact):
    if source.count(exact) != 1:
        raise WorkbenchError("证据或编辑锚点在固定 commit 中必须恰好出现一次。")
    return source[:source.index(exact)].count("\n") + 1


def read_spec(path):
    if not path:
        return {}
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (ValueError, OSError):
        raise WorkbenchError("无法读取证据 JSON。") from None
    if not isinstance(value, dict):
        raise WorkbenchError("证据 JSON 顶层须为对象。")
    for key in ("title", "impact", "expected_behavior", "actual_behavior"):
        if not isinstance(value.get(key), str) or not value[key].strip():
            raise WorkbenchError(f"证据 JSON 缺少 {key}。")
    return value


def policy(snapshot):
    lines = []
    ai_matches = []
    paths = snapshot.policy_paths()
    if snapshot.incomplete or len(paths) > 32:
        raise WorkbenchError("上游政策文件索引不完整或超过读取预算，请人工核对。")
    for path in paths:
        source = snapshot.text(path)
        lines.append(f"- [{inline(path)}]({snapshot.link(path)})")
        for number, line in enumerate(source.splitlines(), 1):
            if AI_LINE.search(line):
                ai_matches.append((path, number, line.strip()[:220]))
    if not paths:
        lines.append("- 在本次文件索引中未发现常见政策文件。")
    lines += [f"- AI 政策线索 [{inline(path)} 第 {number} 行]({snapshot.link(path, number)}) · {inline(line)}"
              for path, number, line in ai_matches[:12]]
    if not ai_matches:
        lines.append("- 已读取所列文本，未找到明确的 AI 政策关键词。仍需核对外链规则。")
    return lines


def search_related(api, snapshot, keywords, kind):
    q = f"repo:{snapshot.repo} is:{kind} {keywords}"
    data = api.get("/search/issues", {"q": q, "per_page": 10})
    return q, data["items"], bool(data["incomplete_results"]), data["total_count"]


def make_patch(snapshot, edits, actual_path, actual_text):
    if not isinstance(edits, list) or not 1 <= len(edits) <= 4:
        raise WorkbenchError("本地补丁需要 1–4 个精确文本编辑。")
    if not any(isinstance(edit, dict) and edit.get("path") == actual_path
               and isinstance(edit.get("before"), str) and actual_text in edit["before"] for edit in edits):
        raise WorkbenchError("补丁应修改已核对的实际行为证据。")
    originals = {}
    replacements = {}
    for edit in edits:
        if (not isinstance(edit, dict) or not all(isinstance(edit.get(key), str) for key in ("path", "before", "after"))
            or not edit["before"] or edit["before"] == edit["after"]):
            raise WorkbenchError("每个编辑须有 path、非空 before 和不同的 after。")
        path = public_path(edit["path"])
        if (not re.fullmatch(r"[A-Za-z0-9_./-]+", path)
            or any(part.casefold() == ".git" or part.endswith(".") or PureWindowsPath(part).is_reserved()
                   for part in path.split("/"))
            or Path(path).suffix.lower() not in {".py", ".md", ".rst", ".txt", ".adoc"}):
            raise WorkbenchError("补丁仅支持安全路径下的 Python、文档和文本文件。")
        if path not in originals:
            originals[path] = snapshot.text(path)
        old = replacements.get(path, originals[path])
        locate(old, edit["before"])
        replacements[path] = old.replace(edit["before"], edit["after"], 1)
    if actual_text in replacements[actual_path]:
        raise WorkbenchError("修改后的文件仍包含实际行为中的旧文本。")

    patch = []
    syntax_checked = []
    for path, new in replacements.items():
        if path.endswith(".py"):
            try:
                ast.parse(new)
            except SyntaxError:
                raise WorkbenchError("修改后的 Python 文件语法解析失败。") from None
            syntax_checked.append(path)
        lines = difflib.unified_diff(
            io_lines(originals[path]), io_lines(new), f"a/{path}", f"b/{path}"
        )
        for line in lines:
            patch.append(line if line.endswith("\n") else line + "\n\\ No newline at end of file\n")
    diff = "".join(patch).encode()
    with tempfile.TemporaryDirectory(prefix="workbench-patch-") as temporary:
        root = Path(temporary)
        for name, source in originals.items():
            path = root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(source.encode())
        git(root, "apply", "--check", "--no-index", "--whitespace=error", "-", data=diff)
        git(root, "apply", "--no-index", "--whitespace=error", "-", data=diff)
        if any((root / name).read_bytes() != source.encode() for name, source in replacements.items()):
            raise WorkbenchError("应用补丁后的字节与计划不一致。")
    return diff, syntax_checked


def io_lines(value):
    if not value:
        return []
    *lines, last = value.split("\n")
    return [line + "\n" for line in lines] + ([last] if last else [])


def pr_template_sections(spec):
    output = []
    sections = spec.get("pr_checklists", [])
    if not isinstance(sections, list):
        raise WorkbenchError("pr_checklists 须为数组。")
    for section in sections:
        if (not isinstance(section, dict) or not isinstance(section.get("heading"), str)
            or not isinstance(section.get("items"), list)):
            raise WorkbenchError("PR 模板清单需要 heading 和 items。")
        output += [f"### {inline(section['heading'])}", ""]
        for item in section["items"]:
            if (not isinstance(item, dict) or not isinstance(item.get("label"), str)
                or not isinstance(item.get("checked"), bool)):
                raise WorkbenchError("PR 模板勾选项需要 label 和布尔值 checked。")
            output.append(f"- [{'x' if item['checked'] else ' '}] {inline(item['label'])}")
        output += [""]
    return output


def contribution_draft(api, args):
    terms(args.keywords)
    snapshot = api.snapshot(args.repo, args.ref)
    spec = read_spec(args.evidence)
    report = [
        "# 上游贡献草稿", "",
        f"目标 · [{inline(snapshot.repo)}]({snapshot.commit_link})  ",
        f"核对 commit · {snapshot.sha}  ",
        f"类别 · {KINDS[args.kind]}", "",
        "## 贡献规则", "", *policy(snapshot), "",
        "## 已有 Issue 和 PR", "",
    ]
    results = {}
    incomplete = False
    for kind, label in (("issue", "Issue"), ("pr", "PR")):
        query, rows, partial, count = search_related(api, snapshot, args.keywords, kind)
        results[kind] = rows
        incomplete |= partial or count > len(rows)
        report.append(f"- {label} 查询 · `{query}`，检索命中 {count} 条，展示 {len(rows)} 条。")
        report += [f"  - [#{row['number']} {inline(row['title'])}]({issue_link(snapshot, row)}) · {row['state']}"
                   for row in rows]
    if incomplete:
        report += ["- 命中超出本次读取范围或 GitHub 返回不完整结果，继续核对后才能判定是否重复。"]
    issue = None
    if args.issue:
        issue = api.get(f"{snapshot.endpoint}/issues/{args.issue}")
        if "pull_request" in issue:
            raise WorkbenchError("--issue 指向 PR，请填写对应 Issue 编号。")
    elif args.kind == "good-first":
        label = api.get("/search/issues", {
            "q": f'repo:{snapshot.repo} is:issue is:open no:assignee label:"good first issue" {args.keywords}',
            "per_page": 1,
        })
        issue = next(iter(label["items"]), None)
    if issue and args.kind == "good-first" and not any(
        item["name"].casefold() == "good first issue" for item in issue["labels"]
    ):
        raise WorkbenchError("指定 Issue 没有维护者设置的 good first issue 标签。")
    if issue:
        report += [f"- 本次关联 [#{issue['number']} {inline(issue['title'])}]({issue_link(snapshot, issue)})"
                   f" · {issue['state']}。沿用该 Issue 讨论。"]

    if not spec:
        if args.patch:
            raise WorkbenchError("生成补丁需要提供证据 JSON。")
        report += ["", "## 单个待核对候选", ""]
        if issue is None and results["issue"] and args.kind != "good-first":
            row = results["issue"][0]
            report += [f"- [#{row['number']} {inline(row['title'])}]({issue_link(snapshot, row)})"]
        elif issue is None:
            report += ["- 当前查询没有可选候选。"]
        report += ["- 请补充影响、预期行为、实际行为及精确源码证据。"]
        return report

    expected_path, expected_text = claim(spec, "expected")
    actual_path, actual_text = claim(spec, "actual")
    expected_line = locate(snapshot.text(expected_path), expected_text)
    actual_line = locate(snapshot.text(actual_path), actual_text)
    if expected_path == actual_path and expected_line == actual_line:
        raise WorkbenchError("预期与实际证据应指向不同的行或文件。")
    related_clear = args.related_reviewed or not (incomplete or results["issue"] or results["pr"])
    draft_kind = "Issue 草稿" if not issue and args.route == "issue" and related_clear else "贡献候选"
    report += [
        "", f"## {draft_kind} · {inline(spec['title'])}", "",
        f"- 影响 · {inline(spec['impact'])}",
        f"- 预期 · {inline(spec['expected_behavior'])}",
        f"- 实际 · {inline(spec['actual_behavior'])}",
        f"- 预期证据 [{inline(expected_path)} 第 {expected_line} 行]({snapshot.link(expected_path, expected_line)})",
        f"- 实际证据 [{inline(actual_path)} 第 {actual_line} 行]({snapshot.link(actual_path, actual_line)})",
    ]
    if not issue and args.route == "direct-pr":
        report += ["- 按人工核对的上游规则准备直接 PR。" if related_clear
                   else "- 提交前核对相似命中，确认没有重复 PR 或相关 Issue。"]
    elif draft_kind == "贡献候选" and not issue:
        report += ["- 发布前确认相关命中是否覆盖同一问题。"]
    if args.patch:
        if not args.policy_reviewed:
            raise WorkbenchError("生成补丁前，请阅读报告中的政策链接并确认 --policy-reviewed。")
        template_sections = pr_template_sections(spec)
        diff, syntax_checked = make_patch(snapshot, spec.get("edits"), actual_path, actual_text)
        with args.patch.open("xb") as stream:
            stream.write(diff)
        report += [
            "", "## PR 草稿", "", f"### {inline(spec['title'])}", "",
            *template_sections, "### Description", "",
            f"{inline(spec['impact'])}", "",
            f"Expected behavior after the change: {inline(spec['expected_behavior'])}", "",
        ]
        if issue:
            report += [f"Related issue: [#{issue['number']}]({issue_link(snapshot, issue)}).", ""]
        report += [
            "### Verification", "",
            "- Checked the evidence and exact edit anchors against the pinned upstream commit.",
            "- Ran `git apply --check --no-index --whitespace=error` on the upstream files, applied the patch, and compared the result byte for byte.",
            *[f"- Parsed the updated {inline(path)} with Python's AST parser." for path in syntax_checked],
            "- Upstream tests, documentation builds, and runtime checks remain pending.",
        ]
        if isinstance(spec.get("assistance"), str) and spec["assistance"]:
            report += [f"- Prepared with assistance from {inline(spec['assistance'])}."]
        if spec.get("submission_note"):
            report += ["", f"提交条件 · {inline(spec['submission_note'])}"]
        report += ["", "在 Chrome 发布前，核对目标、对应 Issue、上游模板与政策、正文和本地补丁。"]
    return report
